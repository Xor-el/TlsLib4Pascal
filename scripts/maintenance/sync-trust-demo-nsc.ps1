# Wire the SystemTrustDemo network-security-config into the Android build (pin cell of the OS-and-host-roots demo).
# Usage:
#   .\sync-trust-demo-nsc.ps1            apply (idempotent)
#   .\sync-trust-demo-nsc.ps1 -Remove    undo
# Writes the untracked SystemTrustDemo.NetworkSecurity.deployproj next to the demo project (SystemTrustDemo.dproj
# imports it when present) and adds android:networkSecurityConfig to the local AndroidManifest.template.xml.
# Re-run after the IDE regenerates the manifest template.

param(
    [string]$RepoRoot = (Resolve-Path (Join-Path $PSScriptRoot "..\..")).Path,
    [string]$AppDeployFolderName = "SystemTrustDemo",
    [switch]$Remove
)

$DemoDir = Join-Path $RepoRoot "TlsLib.Trust.System\Examples\Delphi"
$DeployPath = Join-Path $DemoDir "SystemTrustDemo.NetworkSecurity.deployproj"
$ManifestPath = Join-Path $DemoDir "AndroidManifest.template.xml"
$ConfigPath = Join-Path $DemoDir "res\xml\network_security_config.xml"
$Attribute = 'android:networkSecurityConfig="@xml/network_security_config"'

if (-not (Test-Path $ConfigPath)) {
    Write-Error "network_security_config.xml not found: $ConfigPath"
    exit 1
}

$utf8NoBom = New-Object System.Text.UTF8Encoding $false

if ($Remove) {
    if (Test-Path $DeployPath) { Remove-Item $DeployPath }
    if (Test-Path $ManifestPath) {
        $text = [System.IO.File]::ReadAllText($ManifestPath)
        $text = [regex]::Replace($text, "[ \t]*$([regex]::Escape($Attribute))\r?\n", "")
        [System.IO.File]::WriteAllText($ManifestPath, $text, $utf8NoBom)
    }
    Write-Host "Removed the network-security-config wiring"
    exit 0
}

$deploy = @"
<Project xmlns="http://schemas.microsoft.com/developer/msbuild/2003">
    <!-- Generated by scripts/maintenance/sync-trust-demo-nsc.ps1 - do not edit by hand -->
    <ItemGroup Condition="'`$(Platform)'=='Android64'">
        <DeployFile Include="res\xml\network_security_config.xml">
            <RemoteDir>$AppDeployFolderName\res\xml\</RemoteDir>
            <RemoteName>network_security_config.xml</RemoteName>
            <DeployClass>File</DeployClass>
            <Operation>1</Operation>
            <LocalCommand/>
            <RemoteCommand/>
            <Overwrite>True</Overwrite>
        </DeployFile>
    </ItemGroup>
</Project>
"@
[System.IO.File]::WriteAllText($DeployPath, $deploy, $utf8NoBom)
Write-Host "Wrote $DeployPath"

if (-not (Test-Path $ManifestPath)) {
    Write-Warning "AndroidManifest.template.xml not found in $DemoDir; build the demo for Android once so the IDE creates it, then re-run this script"
    exit 0
}
$manifest = [System.IO.File]::ReadAllText($ManifestPath)
if ($manifest.Contains($Attribute)) {
    Write-Host "Manifest template already carries the attribute"
    exit 0
}
$anchor = [regex]::Match($manifest, '(?m)^([ \t]*)android:persistent=')
if (-not $anchor.Success) {
    Write-Error "No android:persistent attribute in the manifest template to anchor on; add $Attribute to the <application> element by hand"
    exit 1
}
$indent = $anchor.Groups[1].Value
$eol = if ($manifest.Contains("`r`n")) { "`r`n" } else { "`n" }
$manifest = $manifest.Insert($anchor.Index, "$indent$Attribute$eol")
[System.IO.File]::WriteAllText($ManifestPath, $manifest, $utf8NoBom)
Write-Host "Added the attribute to $ManifestPath"
